def mutations(document: dict) -> list[tuple[str, dict]]:
    """One broken profile per rule worth pinning, built from a real one."""
    result: list[tuple[str, dict]] = []

    def variant(name: str, mutate) -> None:
        candidate = copy.deepcopy(document)
        mutate(candidate)
        result.append((name, candidate))

    variant("schema", lambda value: value.__setitem__("schema", "other"))
    variant("schema-version",
            lambda value: value.__setitem__("schema_version", 2))
    variant("no-revisions", lambda value: value.__setitem__("revisions", []))
    variant("capabilities-not-strings",
            lambda value: value.__setitem__("capabilities", [1]))
    variant("capability-not-identifier",
            lambda value: value.__setitem__("capabilities", ["Not An Id"]))
    variant("duplicate-capability",
            lambda value: value.__setitem__("capabilities", ["a", "a"]))
    variant("no-resources", lambda value: value.__setitem__("resources", []))
    variant("resource-missing-kind",
            lambda value: value["resources"][0].pop("kind"))
    variant("resource-id-not-identifier",
            lambda value: value["resources"][0].__setitem__("id", "Bad Id"))
    variant("resource-parameters-not-object",
            lambda value: value["resources"][0].__setitem__("parameters", []))
    variant("duplicate-resource-id",
            lambda value: value["resources"].__setitem__(
                0, {**value["resources"][0],
                    "id": value["resources"][-1]["id"]}))
    variant("profile-version-not-positive",
            lambda value: value.__setitem__("profile_version", 0))
    variant("id-not-identifier", lambda value: value.__setitem__("id", "Nope"))
    variant("revision-size-not-positive",
            lambda value: value["revisions"][0].__setitem__("size", 0))
    variant("revision-sha1-wrong",
            lambda value: value["revisions"][0].__setitem__("sha1", "abc"))
    variant("revision-sha256-wrong",
            lambda value: value["revisions"][0].__setitem__("sha256", "abc"))
    variant("revision-mapper-negative",
            lambda value: value["revisions"][0].__setitem__("mapper", -1))
    variant("revision-missing-name",
            lambda value: value["revisions"][0].pop("name"))
    variant("unknown-resource-payload",
            lambda value: value["resources"][0].__setitem__("payload", "absent"))
    variant("payload-storage-unsupported",
            lambda value: _first_payload(value).__setitem__("storage", "other"))
    variant("payload-sha1-wrong",
            lambda value: _first_payload(value).__setitem__("sha1", "abc"))
    variant("payload-size-not-positive",
            lambda value: _first_payload(value).__setitem__("size", 0))
    variant("override-unknown-resource", _override_unknown)
    variant("resources-and-overrides",
            lambda value: value["revisions"][0].__setitem__(
                "resource_overrides", [{"id": value["resources"][0]["id"]}]
            ) or value["revisions"][0].__setitem__(
                "resources", value["resources"]))

    return result


def _first_payload(document: dict) -> dict:
    for revision in document["revisions"]:
        payloads = revision.get("payloads") or []
        if payloads:
            return payloads[0]
    raise SystemExit("no packaged revision carries a payload to mutate")


def _override_unknown(document: dict) -> None:
    revision = document["revisions"][0]
    revision.pop("resources", None)
    revision["resource_overrides"] = [{"id": "no-such-resource"}]


def render() -> str:
    from retrolarium_kit.authoring import AuthoringError
    from retrolarium_kit.game_profiles import parse_game_profile

    lines = [
        f"schema {SCHEMA}",
        f"schema_version {SCHEMA_VERSION}",
        "generator retrolarium_kit.game_profiles",
    ]

    for path in packaged():
        lines.append(f"accept {path.name}")
        lines.append("end")

    # The synthetic profile is carried whole: it is the only accept case whose
    # bytes the corpus itself supplies.
    base = synthetic_base()
    projection = json.dumps(
        render_profile(parse_game_profile(base)), indent=2, sort_keys=True)
    lines.append("accept-inline synthetic")
    lines.append("source " + json.dumps(base).encode("utf-8").hex())
    lines.append("projection " + projection.encode("utf-8").hex())
    lines.append("end")

    for name, document in mutations(base):
        try:
            parse_game_profile(document)
        except AuthoringError as error:
            message = str(error)
        else:
            raise SystemExit(f"{name} was accepted; the corpus expects a refusal")
        lines.append(f"reject {name}")
        lines.append("source " + json.dumps(document).encode("utf-8").hex())
        lines.append("message " + message.encode("utf-8").hex())
        lines.append("end")

    return "\n".join(lines) + "\n"


def copies() -> dict[Path, str]:
    """Profile copies and their expected projections, as readable files.

    Hex in the corpus would double the size and make a mismatch unreadable in
    a diff; these are the two things worth seeing when one changes.
    """
    from retrolarium_kit.game_profiles import parse_game_profile

    result: dict[Path, str] = {}
    for path in packaged():
        payload = path.read_text(encoding="utf-8")
        result[FIXTURES / path.name] = payload
        projection = json.dumps(
            render_profile(parse_game_profile(json.loads(payload))),
            indent=2, sort_keys=True)
        result[FIXTURES / (path.stem + ".projection.json")] = projection + chr(10)
    return result


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    positional = [value for value in argv[1:] if not value.startswith("-")]
    if len(positional) != 1:
        print(__doc__, file=sys.stderr)
        return 2

    corpus = render()
    output = Path(positional[0])
    wanted = copies()

    if check:
        stale = []
        if not output.is_file() or output.read_text(encoding="utf-8") != corpus:
            stale.append(str(output))
        for path, payload in wanted.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != payload:
                stale.append(str(path))
        if stale:
            print(
                "stale; rerun without --check to regenerate:\n  "
                + "\n  ".join(stale),
                file=sys.stderr,
            )
            return 1
        print(f"{output}: up to date")
        return 0

    FIXTURES.mkdir(parents=True, exist_ok=True)
    for path, payload in wanted.items():
        path.write_text(payload, encoding="utf-8", newline="")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(corpus, encoding="utf-8", newline="\n")
    print(f"{output}: {len(packaged())} packaged profiles, "
          f"{len(mutations(synthetic_base()))} refusals")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
