#!/usr/bin/env python3
"""Emit the game-profile corpus from the Python oracle.

The packaged profiles are the interesting input, so they are copied verbatim
into the core's fixtures rather than paraphrased: a profile that changes in the
Kit makes both the copy and the corpus stale, and --check says so.

Each packaged profile also gets its expected projection beside it, as readable
JSON rather than hex, so a mismatch shows up in a diff.

Refusals are generated by mutating a small synthetic profile, and the mutated
JSON is carried in the corpus so the C++ loader is handed the same bytes.

Usage:
    python retrolarium_core/tools/generate-game-profile-golden.py <out.txt> [--check]
"""

from __future__ import annotations

import copy
import json
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "retrolarium_kit" / "src"))

PROFILE_SOURCE = (
    REPO_ROOT / "retrolarium_kit" / "src" / "retrolarium_kit" / "profiles"
)
FIXTURES = REPO_ROOT / "retrolarium_core" / "tests" / "fixtures" / "game_profiles"

SCHEMA = "retrolarium.game-profile-golden"
SCHEMA_VERSION = 1


def packaged() -> list[Path]:
    return sorted(PROFILE_SOURCE.glob("game_*.json"))


def render_resource(resource) -> dict:
    return {
        "id": resource.resource_id,
        "kind": resource.kind,
        "codec": resource.codec,
        "capacity_policy": resource.capacity_policy,
        "parameters": dict(resource.parameters),
        "payload": resource.payload,
    }


def merged_changes(profile, revision) -> list[dict] | None:
    if revision.resources is not None or not revision.resource_overrides:
        return None
    declared = list(profile.resources)
    merged = list(profile.resources_for(revision))
    if len(declared) != len(merged):
        raise SystemExit(
            f"{profile.game_id}/{revision.revision_id}: merging changed the "
            "resource count, which the projection does not model"
        )
    return [
        render_resource(after)
        for before, after in zip(declared, merged)
        if before != after
    ]


def render_profile(profile) -> dict:
    revisions = []
    for revision in profile.revisions:
        revisions.append({
            "id": revision.revision_id,
            "name": revision.name,
            "size": revision.size,
            "sha1": revision.sha1,
            "sha256": revision.sha256,
            "container": revision.container,
            "mapper": revision.mapper,
            "capabilities": (
                list(revision.capabilities)
                if revision.capabilities is not None else None
            ),
            "resources": (
                [render_resource(item) for item in revision.resources]
                if revision.resources is not None else None
            ),
            "resource_overrides": [
                {
                    "id": item.resource_id,
                    "parameters": dict(item.parameters),
                    "payload": item.payload,
                }
                for item in revision.resource_overrides
            ],
            "payloads": [
                {
                    "id": item.payload_id,
                    "storage": item.storage,
                    "size": item.size,
                    "sha1": item.sha1,
                    "file_offset": item.file_offset,
                    "record_ids": list(item.record_ids),
                    "load_address": item.load_address,
                }
                for item in revision.payloads
            ],
            # What merging actually contributed, and nothing else. A revision
            # with its own list already has it above; one with neither gets the
            # profile's list by definition. Only the entries an override
            # changed carry information, and listing them still catches a merge
            # that touched an entry it should not have.
            "merged_resources": merged_changes(profile, revision),
        })
    return {
        "id": profile.game_id,
        "profile_version": profile.profile_version,
        "name": profile.name,
        "platform": profile.platform,
        "capabilities": list(profile.capabilities),
        "revisions": revisions,
        "resources": [render_resource(item) for item in profile.resources],
    }


